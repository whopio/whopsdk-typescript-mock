export function disputeReason(value: unknown): string {
  const reason = String(value ?? "");
  const key = reason.split(":")[0].replaceAll("_", " ").trim().toUpperCase();
  return (
    codes[key] ??
    matchers.find(([, pattern]) =>
      pattern.test(reason.trim().toLowerCase()),
    )?.[0] ??
    "other"
  );
}
