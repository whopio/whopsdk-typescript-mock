import type { ResourceRecord } from "./types.js";
import { object } from "./current-responses.js";

/** A valid synthetic receipt, not Whop's production invoice layout or tax calculation. */
export function receiptPdf(payment: ResourceRecord): Uint8Array {
  const total = object(payment.total);
  const label = `Test receipt ${payment.id} - ${total.amount} ${total.currency}`
    .replace(/[\\()]/g, "\\$&")
    .replace(/[^\x20-\x7e]/g, "?");
  const stream = `BT /F1 12 Tf 50 740 Td (${label}) Tj ET`;
  const objects = [
    "<< /Type /Catalog /Pages 2 0 R >>",
    "<< /Type /Pages /Kids [3 0 R] /Count 1 >>",
    "<< /Type /Page /Parent 2 0 R /MediaBox [0 0 612 792] /Resources << /Font << /F1 4 0 R >> >> /Contents 5 0 R >>",
    "<< /Type /Font /Subtype /Type1 /BaseFont /Helvetica >>",
    `<< /Length ${Buffer.byteLength(stream)} >>\nstream\n${stream}\nendstream`,
  ];
  let text = "%PDF-1.4\n";
  const offsets = [0];
  objects.forEach((object, index) => {
    offsets.push(Buffer.byteLength(text));
    text += `${index + 1} 0 obj\n${object}\nendobj\n`;
  });
  const start = Buffer.byteLength(text);
  text += `xref\n0 6\n0000000000 65535 f \n${offsets
    .slice(1)
    .map((n) => `${String(n).padStart(10, "0")} 00000 n \n`)
    .join("")}trailer\n<< /Size 6 /Root 1 0 R >>\nstartxref\n${start}\n%%EOF\n`;
  return Buffer.from(text);
}
